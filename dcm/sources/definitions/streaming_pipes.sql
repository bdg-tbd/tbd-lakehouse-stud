-- Streaming ingestion: the local bridge (`mise run bridge`) writes Pub/Sub events through these
-- Snowpipe Streaming pipes (high-performance architecture) into bronze Iceberg tables.
DEFINE PIPE LAKEHOUSE.BRONZE.PIPE_ORDERS_STREAM
  COMMENT = 'Snowpipe Streaming: orders-events -> BRONZE.ORDERS_EVENTS'
AS COPY INTO LAKEHOUSE.BRONZE.ORDERS_EVENTS
  FROM TABLE(DATA_SOURCE(TYPE => 'STREAMING'))
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

DEFINE PIPE LAKEHOUSE.BRONZE.PIPE_CLICKS_STREAM
  COMMENT = 'Snowpipe Streaming: clickstream-events -> BRONZE.CLICKSTREAM_EVENTS'
AS COPY INTO LAKEHOUSE.BRONZE.CLICKSTREAM_EVENTS
  FROM TABLE(DATA_SOURCE(TYPE => 'STREAMING'))
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

GRANT OPERATE, MONITOR ON PIPE LAKEHOUSE.BRONZE.PIPE_ORDERS_STREAM TO ROLE INGEST;
GRANT OPERATE, MONITOR ON PIPE LAKEHOUSE.BRONZE.PIPE_CLICKS_STREAM TO ROLE INGEST;
